/**
 * node build.js
 * Embeds the After Effects importer (ae/geom.jsx + ae/Fig2AE.jsx) into
 * figma-plugin/ui.html, so the plugin saves ONE ready-to-run .jsx:
 * data + importer. In AE: File > Scripts > Run Script File > that file.
 * test/figma.test.js fails if ui.html is stale.
 */
var fs = require('fs');
var path = require('path');

var ROOT = __dirname;
var UI = path.join(ROOT, 'figma-plugin', 'ui.html');
var CEP_RT = path.join(ROOT, 'cep', 'runtime.js');

function src(p) { return fs.readFileSync(path.join(ROOT, p), 'utf8').replace(/^﻿/, ''); }

/** importer source, single file: geom.jsx inlined instead of #include */
function runtime() {
  return src('ae/geom.jsx') + '\n' + src('ae/fontmatch.jsx') + '\n' + src('ae/Fig2AE.jsx').replace(/^#include .*$/gm, '');
}

/**
 * The saved script. Runs in the browser (ui.html, via toString) and in node tests.
 * BOM: ExtendScript reads files without it as ANSI and breaks on non-ASCII.
 * U+2028/2029 are legal in JSON but end a string literal in ES3.
 * Pictures are NOT string literals: ExtendScript needs minutes to parse a few MB
 * of literal, while a comment is just skipped. They go into a trailing comment,
 * one base64 per line, and the importer reads them back from its own file.
 */
function makeJsx(json, rt) {
  var LS = String.fromCharCode(0x2028), PS = String.fromCharCode(0x2029), BOM = String.fromCharCode(0xFEFF);
  var BS = String.fromCharCode(92), NL = String.fromCharCode(10);
  var doc = JSON.parse(json), blobs = [];
  (function walk(ls) {
    for (var i = 0; i < ls.length; i++) {
      var l = ls[i];
      if (!l) continue;
      if (l.png) l.png.ext = l.png.ext === 'jpg' ? 'jpg' : 'png';           // goes into a file name
      if (l.png && l.png.b64) {
        if (!/^[A-Za-z0-9+/=]*$/.test(l.png.b64)) throw new Error('картинка не base64');   // would end the comment
        var at = blobs.indexOf(l.png.b64);
        l.png.ref = at >= 0 ? at : blobs.push(l.png.b64) - 1;
        delete l.png.b64;
      }
      if (l.matte) walk([l.type === 'bgblur' ? l.matte : l.matte.layer]);   // a background blur keeps its mask layer in .matte itself
      if (l.comp) walk(l.comp.layers);
    }
  })(doc.comp.layers);
  json = JSON.stringify(doc).split(LS).join(BS + 'u2028').split(PS).join(BS + 'u2029');
  return BOM + '// Fig2AE: run in After Effects via File > Scripts > Run Script File' + NL +
         'var F2A_DATA = ' + json + ';' + NL + rt + NL +
         '/*F2A-PAYLOAD' + NL + blobs.join(NL) + NL + 'F2A-PAYLOAD-END*/' + NL;
}

function uiHtml() {
  var html = fs.readFileSync(UI, 'utf8');
  var block = '<script>\nvar AE_RUNTIME = ' + JSON.stringify(runtime()).replace(/<\//g, '<\\/') + ';\n' +
              makeJsx.toString() + '\n</script>';
  var out = html.replace(/<!--AE-RUNTIME-->[\s\S]*?<!--\/AE-RUNTIME-->/, function () { return '<!--AE-RUNTIME-->' + block + '<!--/AE-RUNTIME-->'; });
  if (out === html && html.indexOf('<!--AE-RUNTIME-->') < 0) throw new Error('ui.html has no <!--AE-RUNTIME--> marker');
  return out;
}

/** the same importer for the AE-side server (cep/server.js builds the .jsx itself, never runs received code) */
function cepRuntime() {
  return '// generated by `node build.js` — do not edit\nmodule.exports = {\n  runtime: ' + JSON.stringify(runtime()) +
         ',\n  makeJsx: ' + makeJsx.toString() +
         ',\n  fontmatch: (function () {\n' + src('ae/fontmatch.jsx') + '\nreturn F2A_FONTMATCH;\n})()\n};\n';
}

module.exports = { runtime: runtime, makeJsx: makeJsx, uiHtml: uiHtml, cepRuntime: cepRuntime, UI: UI, CEP_RT: CEP_RT };

if (require.main === module) {
  fs.writeFileSync(UI, uiHtml());
  fs.writeFileSync(CEP_RT, cepRuntime());
  console.log('ui.html: importer embedded (' + Math.round(runtime().length / 1024) + ' KB)');
}
